import { copyFile, mkdir, readdir, rm, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { categories, words } from "@tutur/vocab";

const packageDir = fileURLToPath(new URL("..", import.meta.url));
const svgDir = join(packageDir, "svg");
const openmojiSvgDir = join(dirname(createRequire(import.meta.url).resolve("openmoji/package.json")), "color", "svg");

const codes: readonly string[] = [...new Set([...Object.values(words).map((word) => word.symbol), ...categories.map((category) => category.symbol)])].sort();

await mkdir(svgDir, { recursive: true });
for (const file of await readdir(svgDir)) {
  if (!codes.includes(file.replace(/\.svg$/, ""))) await rm(join(svgDir, file));
}
for (const code of codes) {
  await copyFile(join(openmojiSvgDir, `${code}.svg`), join(svgDir, `${code}.svg`));
}

const entries = codes.map((code) => `  "${code}": require("../svg/${code}.svg"),`).join("\n");
await writeFile(
  join(packageDir, "src", "symbols.ts"),
  `// Generated by \`pnpm --filter @tutur/symbols sync\`. Do not edit.
import type { SymbolCode } from "@tutur/vocab";

export const symbols: Record<SymbolCode, number> = {
${entries}
};
`,
);
process.stdout.write(`Synced ${codes.length} OpenMoji symbols.\n`);
