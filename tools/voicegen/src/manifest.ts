import { readFile, writeFile } from "node:fs/promises";
import { z } from "zod";
import type { ClipJob } from "./jobs.ts";

const ManifestEntry = z.object({
  hash: z.string(),
  text: z.string(),
  transcript: z.string(),
  seed: z.number().int(),
  /** "listener" means a person heard the clip and approved it with `--approve` or chose it with `--pin`. */
  verifiedBy: z.enum(["whisper", "listener"]).nullable(),
});
const Manifest = z.record(z.string(), ManifestEntry);

export type Manifest = z.infer<typeof Manifest>;

export async function readManifest(path: string): Promise<Manifest> {
  try {
    return Manifest.parse(JSON.parse(await readFile(path, "utf8")));
  } catch (error) {
    if (error instanceof Error && "code" in error && error.code === "ENOENT") return {};
    throw error;
  }
}

export async function writeManifest(path: string, manifest: Manifest): Promise<void> {
  const sorted = Object.fromEntries(Object.entries(manifest).sort(([a], [b]) => a.localeCompare(b)));
  await writeFile(path, `${JSON.stringify(sorted, null, 2)}\n`);
}

function requireMap(jobs: readonly ClipJob[]): string {
  return jobs.map((job) => `  ${job.id}: require("../clips/${job.key}.mp3"),`).join("\n");
}

/** Metro only bundles assets reached through a literal require(), so the clip map is generated code. */
export function clipModule(jobs: readonly ClipJob[]): string {
  const byGroup = (group: ClipJob["group"]) => jobs.filter((job) => job.group === group);
  return `// Generated by \`pnpm voicegen\`. Do not edit.
import type { PhraseId, WordId } from "@tutur/vocab";

export const wordClips: Record<WordId, number> = {
${requireMap(byGroup("words"))}
};

export const phraseClips: Record<PhraseId, number> = {
${requireMap(byGroup("phrases"))}
};
`;
}
